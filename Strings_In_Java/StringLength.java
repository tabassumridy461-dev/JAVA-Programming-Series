
public class StringLength {
    public static void main(String[] args) {

        String name = "Tabassum";

        // Finding String length
        int length = name.length();

        System.out.println("Name: " + name);
        System.out.println("Length: " + length);

        // Output:
        // Name: Tabassum
        // Length: 8
    }
}
