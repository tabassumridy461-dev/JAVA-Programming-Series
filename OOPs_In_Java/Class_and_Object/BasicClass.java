
public class BasicClass {

    String name = "Tabassum";
    int age = 22;

    public static void main(String[] args) {

        BasicClass obj = new BasicClass();

        System.out.println("Name: " + obj.name);
        System.out.println("Age: " + obj.age);
    }
}

// Output:
