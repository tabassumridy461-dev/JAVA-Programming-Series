public class PrintingOutput {

    public static void main(String[] args) {

        // Print without moving to a new line
        System.out.print("Hello ");

        // Print and move to a new line
        System.out.println("Java!");

        // Print multiple lines
        System.out.println("I am learning Java.");
        System.out.println("This is my Java Programming Series.");

        // Printing numbers
        System.out.println(100);
        System.out.println(25 + 10);

    }
}

/*Output
Hello Java!
I am learning Java.
This is my Java Programming Series.
100
35 */
