public class MathClass {

    public static void main(String[] args) {

        System.out.println("Absolute Value: " + Math.abs(-10));

        System.out.println("Maximum: " + Math.max(20, 30));

        System.out.println("Minimum: " + Math.min(20, 30));

        System.out.println("Square Root: " + Math.sqrt(25));

        System.out.println("Power: " + Math.pow(2, 3));

        System.out.println("Round: " + Math.round(5.6));

        System.out.println("Ceiling: " + Math.ceil(5.3));

        System.out.println("Floor: " + Math.floor(5.8));
    }

    /*
    Output:
    Absolute Value: 10
    Maximum: 30
    Minimum: 20
    Square Root: 5.0
    Power: 8.0
    Round: 6
    Ceiling: 6.0
    Floor: 5.0
    */
}
